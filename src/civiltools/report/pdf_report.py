class EnglishPDF(FPDF):
    """PDF builder for English LTR structural engineering reports."""

    def __init__(self, config: ReportConfig | None = None):
        super().__init__()
        self.config = config or ReportConfig(language="en")
        self._temp_files: list[Path] = []
        self._font_name = self._register_unicode_font()
        self._setup_defaults()

    @staticmethod
    def _find_dejavu() -> Path | None:
        """Locate DejaVu Sans TTF shipped with matplotlib."""
        try:
            ttf = Path(matplotlib.get_data_path()) / "fonts" / "ttf" / "DejaVuSans.ttf"
            if ttf.exists():
                return ttf
        except Exception:
            pass
        return None

    def _register_unicode_font(self) -> str:
        """Add a Unicode TTF font to the PDF and return its family name."""
        ttf = self._find_dejavu()
        if ttf is not None:
            self.add_font("DejaVu", "", str(ttf))
            self.add_font("DejaVu", "B", str(ttf.parent / "DejaVuSans-Bold.ttf"))
            return "DejaVu"
        # Fallback: built-in Helvetica (latin-1 only)
        return "Helvetica"

    def _setup_defaults(self):
        self.set_auto_page_break(auto=True, margin=20)
        self.set_margins(15, 15, 15)

    # ── Header / Footer ───────────────────────────────────────────────
    def header(self):
        self.set_font(self._font_name, "B", 9)
        self.set_text_color(100, 100, 100)
        self.cell(0, 8, "civilTools - Structural Engineering Report", align="C")
        self.ln(10)
        self.set_draw_color(200, 200, 200)
        self.line(15, self.get_y(), self.w - 15, self.get_y())
        self.ln(3)

    def footer(self):
        if self.config.include_page_numbers:
            self.set_y(-15)
            self.set_font(self._font_name, "", 8)
            self.set_text_color(128, 128, 128)
            self.cell(0, 10, f"Page {self.page_no()}/{{nb}}", align="C")

    # ── Content builders ──────────────────────────────────────────────
    def add_title_page(self, title: str, subtitle: str = ""):
        self.add_page()
        self.ln(60)
        self.set_font(self._font_name, "B", 28)
        self.set_text_color(30, 60, 120)
        self.cell(0, 15, title, align="C")
        self.ln(20)
        if subtitle:
            self.set_font(self._font_name, "", 16)
            self.set_text_color(80, 80, 80)
            self.cell(0, 10, subtitle, align="C")
            self.ln(15)
        self.set_font(self._font_name, "", 10)
        self.set_text_color(140, 140, 140)
        self.cell(0, 10, "Generated by civilTools", align="C")
        self.set_text_color(0, 0, 0)

    def add_heading(self, text: str, level: int = 1):
        sizes = {1: 18, 2: 14, 3: 12}
        colors = {1: (30, 60, 120), 2: (50, 100, 50), 3: (80, 80, 80)}
        self.ln(6)
        self.set_font(self._font_name, "B", sizes.get(level, 12))
        self.set_text_color(*colors.get(level, (0, 0, 0)))
        self.cell(0, 10, text, new_x="LMARGIN", new_y="NEXT")
        if level == 1:
            self.set_draw_color(30, 60, 120)
            self.line(15, self.get_y(), self.w - 15, self.get_y())
        self.ln(3)
        self.set_text_color(0, 0, 0)

    def add_paragraph(self, text: str, bold: bool = False):
        style = "B" if bold else ""
        self.set_font(self._font_name, style, 11)
        self.multi_cell(0, 6, text)
        self.ln(3)

    def add_kv_table(self, rows: list[tuple[str, str]]):
        col_w = [70, self.w - 30 - 70]
        self.set_font(self._font_name, "", 10)
        fill = False
        for key, val in rows:
            if fill:
                self.set_fill_color(240, 245, 250)
            self.cell(col_w[0], 7, key, border="LR", fill=fill)
            self.cell(col_w[1], 7, str(val), border="LR", fill=fill)
            self.ln()
            fill = not fill
        self.ln(4)

    def add_data_table(self, headers: list[str], rows: list[list],
                       col_widths: list[float] | None = None):
        n = len(headers)
        available = self.w - 30
        if col_widths is None:
            col_widths = [available / n] * n

        # Header
        self.set_font(self._font_name, "B", 8)
        self.set_fill_color(30, 60, 120)
        self.set_text_color(255, 255, 255)
        for i, h in enumerate(headers):
            self.cell(col_widths[i], 8, h, border=1, fill=True, align="C")
        self.ln()
        self.set_text_color(0, 0, 0)

        # Rows
        self.set_font(self._font_name, "", 8)
        fill = False
        for row in rows:
            if fill:
                self.set_fill_color(245, 248, 252)
            h = 7
            for i, val in enumerate(row):
                w = col_widths[i] if i < len(col_widths) else col_widths[-1]
                self.cell(w, h, str(val)[:40], border=1, fill=fill, align="C")
            self.ln()
            fill = not fill
        self.ln(4)

    def add_df_table(self, df, max_rows: int = 200):
        headers = list(df.columns)
        rows = df.head(max_rows).values.tolist()
        self.add_data_table(headers, rows)

    def add_formula(self, latex_str: str, description: str = ""):
        if description:
            self.set_font(self._font_name, "", 10)
            self.cell(0, 6, description, new_x="LMARGIN", new_y="NEXT")
            self.ln(1)
        try:
            img_bytes = _render_latex(latex_str)
            tmp = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
            tmp.write(img_bytes)
            tmp.close()
            self._temp_files.append(Path(tmp.name))
            self.image(tmp.name, w=140)
            self.ln(3)
        except Exception:
            self.set_font(self._font_name, "", 8)
            self.multi_cell(0, 5, latex_str)
            self.set_font(self._font_name, "", 11)
            self.ln(3)

    def add_image_bytes(self, img_bytes: bytes, w: float = 180):
        tmp = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
        tmp.write(img_bytes)
        tmp.close()
        self._temp_files.append(Path(tmp.name))
        self.image(tmp.name, w=w)
        self.ln(4)

    def save(self, filepath: str | Path):
        self.alias_nb_pages()
        self.output(str(filepath))
        for tmp in self._temp_files:
            try:
                tmp.unlink()
            except OSError:
                pass
        self._temp_files.clear()


