def create_pdf_report(
    data: ReportData,
    config: ReportConfig | None = None,
    output_path: str | Path | None = None,
) -> Path:
    """Generate a full PDF report from extracted data.

    Parameters
    ----------
    data : ReportData
        All report data (from ``extract_report_data``).
    config : ReportConfig, optional
        Report configuration.
    output_path : str | Path, optional
        Output file path.
    """
    config = config or ReportConfig(language="en")
    lang = config.language if config.language != "both" else "en"
    pdf = EnglishPDF(config)
    pdf.alias_nb_pages()

    # Title page
    title = data.project_name or "Structural Report"
    pdf.add_title_page(title, "Structural Engineering Report")

    # Sections
    for section_key in config.active_sections:
        renderer = _SECTION_DISPATCH.get(section_key)
        if renderer:
            renderer(pdf, data, lang)
        else:
            pdf.add_page()
            pdf.add_heading(config.get_section_name(section_key), 1)
            pdf.add_paragraph(f"[Section: {section_key} - content pending]")

    # Save
    if output_path is None:
        stem = (data.project_name or "report").replace(" ", "_")
        output_path = Path(f"{stem}_report.pdf")
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    pdf.save(output_path)
    return output_path
